// Warm the probe caches ONCE, from a single serialized point at companion entry, before the
// status screen's redraw loop and before any stream subscription. The W5500 read-only probe runs
// before the NRF24 one because RF24 begin() writes registers and the two may share a CS.
void companionWarmCaps() {
    s_probeWindow = true;
    (void)companionCc1101Present();
    (void)companionNfcPresent();
    (void)companionLoraPresent();
    (void)companionW5500Present();
    (void)companionNrf24Present();
    (void)companionFmPresent();
    s_probeWindow = false;
}

