// Write one module's evidence; conflicts mentioning it are attached as `conflict`.
static void writeEvidence(
    JsonObject ev, const char *module, const EvidenceInputs &in, const char *detail, const PinList &pins,
    const PinConflict *conflicts, size_t conflictCount
) {
    JsonObject m = ev[module].to<JsonObject>();
    m["level"] = evidenceLevelName(resolveEvidenceLevel(in));
    if (const char *probe = probeOutcomeName(in.probe)) m["probe"] = probe;
    if (detail && detail[0]) m["detail"] = detail;
    JsonArray list;
    for (size_t i = 0; i < conflictCount; i++) {
        const PinUse &a = pins.uses[conflicts[i].a];
        const PinUse &b = pins.uses[conflicts[i].b];
        const PinUse *self = nullptr, *other = nullptr;
        if (strcmp(a.module, module) == 0) self = &a, other = &b;
        else if (strcmp(b.module, module) == 0) self = &b, other = &a;
        if (!self) continue;
        if (list.isNull()) list = m["conflict"].to<JsonArray>();
        JsonObject c = list.add<JsonObject>();
        c["gpio"] = self->gpio;
        c["role"] = self->role;
        c["with"] = other->module;
        c["with_role"] = other->role;
    }
}

static EvidenceInputs probedInputs(ProbeId id, bool compiled, bool configured) {
    EvidenceInputs in;
    in.compiled = compiled;
    in.configured = configured;
    in.probe = s_probe[id].probe;
    in.initialized = s_probe[id].initialized;
    return in;
}

static EvidenceInputs fixedInputs(bool compiled, bool configured) {
    EvidenceInputs in;
    in.compiled = compiled;
    in.configured = compiled && configured;
    return in;
}

