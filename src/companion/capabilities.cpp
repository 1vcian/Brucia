static void writeEvidenceMap(JsonObject d) {
    static PinList pins; // static: keeps ~1 KB off the loop task stack
    pins = PinList();
    collectPinUses(pins);
    PinConflict conflicts[32];
    size_t found = findPinConflicts(pins.uses, pins.count, conflicts, 32);
    if (found > 32) found = 32;

    JsonObject ev = d["evidence"].to<JsonObject>();
    auto probed = [&](const char *name, ProbeId id, bool compiled, bool configured) {
        writeEvidence(ev, name, probedInputs(id, compiled, configured), s_probe[id].detail, pins, conflicts, found);
    };
    auto fixed = [&](const char *name, bool compiled, bool configured, const char *detail) {
        writeEvidence(ev, name, fixedInputs(compiled, configured), detail, pins, conflicts, found);
    };

    fixed("wifi", true, false, "ESP32 SoC radio; driver starts per operation");
    fixed("ble", true, false, "ESP32 SoC radio; driver starts per operation");
    // Uniform for every board: a module not built for this env resolves to level "none".
    probed("cc1101", PR_CC1101, kHasCc1101, cc1101Configured());
    probed("nfc", PR_NFC, true, nfcConfigured());
    probed("nrf24", PR_NRF24, kHasNrf24, nrf24Configured());
    probed("fm", PR_FM, kHasFm, fmConfigured());
    probed("lora", PR_LORA, kHasLora, loraConfigured());
    probed("eth", PR_ETH, kHasEth, w5500Configured());
#if defined(COMPANION_HAS_IR)
    fixed("ir", true, bruceConfigPins.irTx >= 0 || bruceConfigPins.irRx >= 0, "GPIO only; no chip identification");
#else
    fixed("ir", false, false, nullptr);
#endif
#if defined(COMPANION_HAS_MIC)
    fixed("mic", true, true, "board profile pins; no chip identification");
#else
    fixed("mic", false, false, nullptr);
#endif
#if defined(HAS_NS4168_SPKR)
    fixed("speaker", true, true, "board profile I2S pins; no chip identification");
#else
    fixed("speaker", false, false, nullptr);
#endif
#if !defined(LITE_VERSION)
    fixed("ibutton", true, ibuttonPinUsable(bruceConfigPins.iButton, GPIO_NUM_MAX),
          "1-Wire answers only with a key present; not probed");
#else
    fixed("ibutton", false, false, nullptr);
#endif
    // SD: the mount state is live (mounted by Bruce, no probe of ours). Not mounted cannot be told
    // apart from an unreadable or unformatted card, so it is not reported as probed absent.
    {
        EvidenceInputs in;
        in.compiled = true;
#if defined(USE_SD_MMC)
        in.configured = true;
#else
        in.configured = spiPinsSet(bruceConfigPins.SDCARD_bus);
#endif
        in.probe = sdcardMounted ? ProbeOutcome::Present : ProbeOutcome::NotRun;
        writeEvidence(ev, "sd", in, sdcardMounted ? "card mounted" : "not mounted (no card, format or mount failure)",
                      pins, conflicts, found);
    }
}

void sendCaps(uint32_t id) {
    JsonDocument out;
    beginEnvelope(out, MSG_CAPS, id);
    JsonObject d = out["d"].to<JsonObject>();
    d["board"] = COMPANION_BOARD_NAME;
    d["chip"] = companionChip();
    d["fw"] = COMPANION_FW_VERSION;
    d["proto"] = BRUCIA_PROTO_VERSION;

    // Real per-peripheral capability detection (hybrid: compile-time board macros for onboard
    // fixed peripherals, quick runtime probes for the optional/uncertain ones). The app uses
    // this to show/hide features. wifi/ble are always present on these ESP32 targets.
    JsonObject caps = d["caps"].to<JsonObject>();
    caps["cc1101"] = companionCc1101Present();
    caps["nfc"] = companionNfcPresent();
    caps["nrf24"] = companionNrf24Present();
    // FM (Si4713): runtime I2C probe at 0x63 (cached). Absent on the T-Embed/CYD -> fm:false.
    caps["fm"] = companionFmPresent();
#if defined(TXLED) || defined(RXLED) || defined(IR_RX_PINS) || defined(IR_TX_PINS)
    caps["ir"] = true; // onboard IR RX/TX pins (compile-time board macros)
#else
    caps["ir"] = false;
#endif
#if defined(COMPANION_HAS_MIC)
    caps["mic"] = true; // MIC_SPM1423 / MIC_INMP441 (compile-time board macro)
#else
    caps["mic"] = false;
#endif
#if defined(HAS_NS4168_SPKR)
    caps["speaker"] = true; // NS4168 I2S speaker (compile-time board macro)
#else
    caps["speaker"] = false;
#endif
    caps["lora"] = companionLoraPresent();
    // Ethernet (W5500): runtime SPI probe (false when no module is actually attached / not wired).
    caps["eth"] = companionW5500Present();
#if !defined(LITE_VERSION)
    // iButton: configured pin only, not probed (a 1-Wire bus answers only with a key present).
    caps["ibutton"] = ibuttonPinUsable(bruceConfigPins.iButton, GPIO_NUM_MAX);
#else
    caps["ibutton"] = false;
#endif
    caps["wifi"] = true;
    caps["ble"] = true;
    d["features"]["verified_files"] = true; // correlated chunks, size/CRC32 completion, empty/spaced writes
    d["features"]["transactional_uploads"] = true; // staged + size/CRC commit; FAT recovery journal
    d["features"]["mifare_keycheck_report"] = true; // mifare_keycheck ACK carries v1 complete/partial + UID
#if defined(HAS_NS4168_SPKR)
    // speaker_play ACKs at start (d.play) and ends with one EVENT ev="speaker.play"; speaker_stop stops it.
    d["features"]["speaker_play_async"] = true;
#endif
    d["features"]["mifare_keycheck_stop"] = true;   // in-flight mifare_keycheck batch stops on a polled stop frame
    d["features"]["diag"] = true; // `diag` CMD: reset reason, heap and bounded link/drop counters on request
#if !defined(LITE_VERSION)
    // wifi_handshake/wifi_pmkid terminal ACK carries d.desc{v,path,size,crc32,frames,complete,stop,...}
    // for the file written this run; the phone imports exactly that path and verifies it after transfer.
    d["features"]["capture_descriptor"] = true;
#endif

    // Per-module evidence (additive): compiled / configured / probed / initialized, the probe
    // outcome (present / absent / busy), a short detail and static pin conflicts. caps above stays
    // the gating map; evidence explains it. Never claims a physical test.
    writeEvidenceMap(d);

    // Release provenance (additive): ties a report to the exact artifact. fw/proto/features above
    // are not repeated here. dirty is omitted when Git state was unavailable at build time.
    JsonObject build = d["build"].to<JsonObject>();
    build["commit"] = BRUCIA_BUILD_COMMIT;
#if BRUCIA_BUILD_DIRTY >= 0
    build["dirty"] = BRUCIA_BUILD_DIRTY == 1;
#endif
    build["id"] = BRUCIA_BUILD_ID;
    build["time"] = BRUCIA_BUILD_TIME;
    build["time_src"] = BRUCIA_BUILD_TIME_SOURCE;
    build["env"] = BRUCIA_BUILD_ENV;

    // Legacy coarse module list (kept for backward compatibility with older app builds).
    JsonArray modules = d["modules"].to<JsonArray>();
    modules.add("wifi");
    modules.add("ble");
    if (caps["cc1101"].as<bool>()) modules.add("rf");
    if (caps["ir"].as<bool>()) modules.add("ir");
    JsonArray transports = d["transports"].to<JsonArray>();
    transports.add("usb");
    d["mtu"] = COMPANION_MAX_FRAME;
    d["battery"] = getBattery();
    // Brucia: report the device UI theme so the app can match it (the device always wins). priColor
    // is RGB565; ledColor is 0xRRGGBB. The app re-themes its accent + flame to priColor on connect.
    d["theme"] = (uint32_t)bruceConfig.priColor;
#ifdef HAS_RGB_LED
    d["led"] = (uint32_t)bruceConfig.ledColor;
    d["ledBright"] = (int)bruceConfig.ledBright; // 0..100, so the app's slider shows the real value
    d["ledEffect"] = (int)bruceConfig.ledEffect; // 0..9
#endif
    d["bright"] = (int)bruceConfig.bright; // screen brightness 0..100
    sendEnvelope(out);
}

